#!/usr/bin/env python3
"""Builds the generated web files from templates and the shared renderer:
   preview/index.html               the screen preview page
   arduino/ledmatrix/portal_page.h  the portal page, embedded in the firmware
Run after editing preview/index.template.html, portal/portal.template.html, shared/renderer.js
or shared/fonts.json. The portal page also gets the zone table shared/tz_zones.json (made by
tools/make_tz.py) in place of __TZ_TABLE__, as minified JSON, and the list of Google News editions of
arduino/ledmatrix/editions.h as <option> elements in place of __EDITION_OPTIONS__."""
import html, json, os, re
root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
rd = lambda p: open(os.path.join(root, p)).read()
fonts = rd('shared/fonts.json'); renderer = rd('shared/renderer.js').replace('__FONTS__', fonts)
def fill(t): return t.replace('__RENDERER__', renderer)
open(os.path.join(root, 'preview/index.html'), 'w').write(fill(rd('preview/index.template.html')))
tz_table = json.dumps(json.loads(rd('shared/tz_zones.json')), separators=(',', ':'))
def edition_options():
    """The <option> list of the headlines language and region, written from arduino/ledmatrix/editions.h, the one place the list
    is kept: the option value is the index in that list, which is what the board saves. tools/test_editions_portal.py checks the result."""
    rows = re.findall(r'^\s*\{"([^"]+)", "([^"]+)", "([^"]+)", "([^"]+)"\},\s*$', rd('arduino/ledmatrix/editions.h'), re.M)
    assert 8 <= len(rows) <= 40, 'editions.h: %d entries found' % len(rows)
    return ''.join('<option value="%d">%s</option>' % (i, html.escape(r[0])) for i, r in enumerate(rows))
portal = fill(rd('portal/portal.template.html')).replace('__TZ_TABLE__', tz_table).replace('__EDITION_OPTIONS__', edition_options())
assert '__EDITION_OPTIONS__' not in portal and '__TZ_TABLE__' not in portal
assert ')PORTAL"' not in portal
header = ('// Generated by tools/build_web.py from portal/portal.template.html. Do not edit.\n#pragma once\n#include <pgmspace.h>\n\n'
          'static const char PORTAL_HTML[] PROGMEM = R"PORTAL(' + portal + ')PORTAL";\n')
open(os.path.join(root, 'arduino/ledmatrix/portal_page.h'), 'w').write(header)
print('preview/index.html', os.path.getsize(os.path.join(root, 'preview/index.html')), 'bytes;',
      'portal_page.h', os.path.getsize(os.path.join(root, 'arduino/ledmatrix/portal_page.h')), 'bytes')
